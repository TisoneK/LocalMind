"""
Agent data models — pure dataclasses, no business logic.

Kept separate so that engine.py, tests, and UI serialization layers
can import AgentStep / AgentTrace without pulling in the full loop.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Optional


@dataclass
class AgentStep:
    """Record of a single iteration inside the agent loop."""

    iteration: int
    thought: str
    tool_name: Optional[str]
    tool_input: Optional[str]
    observation: Optional[str]
    reflection: Optional[str] = None
    tool_failed: bool = False
    retry_count: int = 0
    latency_ms: int = 0
    phase: str = "execute"
    """Phase of the workflow: 'plan', 'execute', 'verify', or 'final'."""


@dataclass(frozen=True)
class WorkReportEntry:
    """Evidence returned by one worker/tool operation."""

    tool_name: str
    tool_input: str
    observation: str
    succeeded: bool


# The internal evidence-recap header. This format exists for the USER-facing
# fallback stream only; it must never re-enter a model prompt (models that see
# it in their own history start mimicking it into their answers), so history
# feeds strip complete blocks via strip_worker_reports().
WORK_REPORT_HEADER = "Worker report — tool execution evidence:"

# A rendered block: the optional plain-language lead-in (render_user_fallback's
# honest framing — stripped WITH the block so model-bound history keeps neither),
# the header line, the optional iteration-limit note, then numbered
# "N. tool(input) — status" lines each optionally followed by an indented
# "Output: …" line. Entry/Output shapes tolerate the small drift models
# introduce when mimicking the format (")" numbering, 1–4 space indents); a
# block still requires the exact header plus at least one entry.
_WORK_REPORT_LEAD = (
    r"(?:I could not produce a clean final answer from these steps\. "
    r"Here is exactly what ran and what came back:\n\n)?"
)
_WORK_REPORT_BLOCK_PATTERN = re.compile(
    _WORK_REPORT_LEAD
    + re.escape(WORK_REPORT_HEADER)
    + r"(?:\nThe agent loop reached its iteration limit after these operations:)?"
    + r"(?:\n[0-9]+[.)] .*(?:\n {1,4}Output: .*)?)+",
)


def strip_worker_reports(text: str) -> str:
    """Remove rendered worker-report blocks from model-bound or model-authored text.

    Two callers:
    - history feeds: a deterministic report appended to a past assistant
      message must never be shown back to the model (it would learn the
      format and reproduce it in future answers);
    - the emission boundary: if a model mimics the format anyway, the block
      is dropped so the deterministic renderer stays the only author.

    Prose that merely mentions a worker report is untouched — only a complete
    block (header + at least one numbered entry) matches.
    """
    if not text or WORK_REPORT_HEADER not in text:
        return text
    cleaned = _WORK_REPORT_BLOCK_PATTERN.sub("", text)
    # Collapse blank runs left by removal (max 2 consecutive newlines).
    cleaned = re.sub(r"\n{3,}", "\n\n", cleaned)
    return cleaned


def strip_worker_reports_from_history(messages: list) -> list:
    """Return ``messages`` with worker-report blocks stripped from assistant turns.

    For prompt-bound history lists of ``{role, content}`` dicts. Non-dict
    items and non-assistant turns pass through untouched.
    """
    return [
        {**m, "content": strip_worker_reports(m.get("content", ""))}
        if isinstance(m, dict) and m.get("role") == "assistant"
        else m
        for m in messages
    ]


# A final answer at least this long is treated as substantive
# and NEVER gets the deterministic evidence report appended — the execution
# trace is already visible via the inline action cards + Actions tab.
_SUBSTANTIVE_ANSWER_MIN_CHARS = 40


@dataclass(frozen=True)
class WorkReport:
    """Structured worker report used at the tool-to-user boundary.

    The report is deliberately deterministic: it is derived from the trace,
    not generated by another model call. This gives the orchestrator a stable
    report-back contract when model synthesis is empty or merely a heading.
    """

    entries: tuple[WorkReportEntry, ...] = ()
    hit_limit: bool = False

    @classmethod
    def from_trace(cls, trace: "AgentTrace") -> "WorkReport":
        return cls(
            entries=tuple(
                WorkReportEntry(
                    tool_name=step.tool_name or "",
                    tool_input=step.tool_input or "",
                    observation=step.observation or "",
                    succeeded=not step.tool_failed,
                )
                for step in trace.steps
                if step.tool_name
            ),
            hit_limit=trace.hit_limit,
        )

    def needs_report(self, response: str) -> bool:
        """Return whether a response needs the deterministic evidence report.

        The chat message owns the FINAL ANSWER only. The
        execution trace is already visible to the user via the inline action
        cards (chat) and the Actions tab — so a substantive answer is never
        appended with a recap, even if it doesn't quote raw evidence tokens
        ("Working tree is clean — no uncommitted changes" must NOT become
        "… Worker report — tool execution evidence: 1. git(status) …").

        The report is reserved for actual silent failures: an empty or
        trivially short response (the fallback contract), or the
        iteration-limit path where the model may have been cut off mid-work
        and could have fabricated a conclusion.
        """
        if not self.entries:
            return False
        stripped = response.strip()
        if not stripped:
            return True

        # Evidence comes from tool observations AND inputs. Observations are
        # the primary source; inputs are included so an answer naming the
        # actual written file ("Created hello.py successfully.") counts as
        # quoting its evidence, while a command echo like ``ls Dev`` still
        # contributes nothing (2-3 char tokens are below the match floor).
        evidence_tokens: set[str] = set()
        ignored = {
            "true", "false", "none", "null", "okay", "success",
            "successful", "status", "result", "output", "tool",
            "command", "completed",
        }
        for entry in self.entries:
            for source in (entry.observation, entry.tool_input):
                if not source.strip():
                    continue
                for token in re.findall(
                    r"[a-z0-9][a-z0-9_.:/\\-]{3,}", source.lower()
                ):
                    if token not in ignored:
                        evidence_tokens.add(token)

        if self.hit_limit:
            # Iteration-limit path: keep the evidence-token check — the model
            # was cut off and its conclusion may be fabricated.
            if not evidence_tokens:
                return False
            normalized_response = stripped.lower()
            matched_tokens = sum(
                token in normalized_response for token in evidence_tokens
            )
            required_tokens = min(2, len(evidence_tokens))
            return matched_tokens < required_tokens

        # Normal completion: a substantive-length answer always stands alone
        # — the execution trace is already visible via the inline action cards
        # and Actions tab, so "Working tree is clean — no uncommitted
        # changes" must NEVER become "… Worker report — …". The threshold is
        # deliberately conservative: anything this long is a real answer, and
        # anything shorter only gets the report if it quotes no evidence.
        if len(stripped) >= _SUBSTANTIVE_ANSWER_MIN_CHARS:
            return False
        # Short answers: only acceptable if they actually quote the evidence
        # that ran. A terse filler like "Got it — working on your request…"
        # (the silent-stall shape) gets the report.
        if not evidence_tokens:
            return False
        matched_tokens = sum(
            token in stripped.lower() for token in evidence_tokens
        )
        return matched_tokens < min(2, len(evidence_tokens))

    def render(self) -> str:
        """Render the deterministic report for the user-facing stream."""
        if not self.entries:
            return ""

        lines = [WORK_REPORT_HEADER]
        if self.hit_limit:
            lines.append("The agent loop reached its iteration limit after these operations:")
        for index, entry in enumerate(self.entries, 1):
            status = "succeeded" if entry.succeeded else "failed"
            tool_input = entry.tool_input.strip() or "(no input recorded)"
            lines.append(f"{index}. {entry.tool_name}({tool_input}) — {status}")
            output = entry.observation.strip() or "(no output returned)"
            if len(output) > 500:
                output = output[:497] + "..."
            lines.append(f"   Output: {output}")
        return "\n".join(lines)

    def render_user_fallback(self) -> str:
        """Render the report as the LAST-RESORT user-facing answer.

        A bare step list reads like internal thought pasted into the chat —
        the user never asked for evidence, they asked for an answer. This
        says plainly that the clean answer failed and the steps are the
        honest remainder, so the block reads as a fallback, not a leak.
        Contract note: the leading sentence sits OUTSIDE the report block,
        so `strip_worker_reports` and `needs_report` matching (both keyed on
        the header) are untouched.
        """
        rendered = self.render()
        if not rendered:
            return ""
        return (
            "I could not produce a clean final answer from these steps. "
            "Here is exactly what ran and what came back:\n\n" + rendered
        )


@dataclass
class AgentTrace:
    """Accumulated trace for a complete agent run."""

    steps: list[AgentStep] = field(default_factory=list)
    final_response: str = ""
    iterations_used: int = 0
    hit_limit: bool = False
    limit_kind: str = ""
    """Which budget actually ended the loop: 'iteration_cap' (base failsafe),
    'wall_clock' (time cap), or 'hard_ceiling' (runaway guard). Empty when
    hit_limit is False. The wall-clock break used to be reported
    as 'iteration_limit' — the same misdiagnosis class
    fallback-wording contract warns about (a time cap is NOT a step-count
    cap; the remedies differ)."""
    clarification_issued: bool = False
    tool_talk_recoveries: int = 0  # how many times tool-talk was detected and suppressed
    tool_forced_recoveries: int = 0  # forced-tool reprompts (empty/text-without-tool on iter-0)
    empty_reasoning_recoveries: int = 0  # bounded retries after an
    # empty-but-reasoned response (thinking streamed, no content/tool call)
    plan_text: str = ""
    """Text of the planning phase output (empty if planning was skipped)."""
    task_type: str = ""
    """Task type the agent settled on during planning (the settled-routing
    re-key). '' = legacy no-op policy / no explicit type. The dispatcher's
    task_type is only a hint; the settled value keys memory levels + policy."""
    verification_results: list[str] = field(default_factory=list)
    """Results from post-execution verification checks."""
    success_criteria: list[str] = field(default_factory=list)
    """Typed success criteria from the dispatcher / create_plan."""
    criteria_results: list[tuple[str, bool, str]] = field(default_factory=list)
    """Acceptance-gate evaluation: [(criterion, passed, note)]."""
    gate_passed: Optional[bool] = None
    """Whether the acceptance gate passed at turn end (None = no criteria)."""
    gate_summary: str = ""
    """One-line gate outcome for the user-facing final answer."""
    thinker_analysis: str = ""
    """User-facing rendering of the Thinker's analysis, preserved
    on the trace so the degraded-evidence fallback can surface the
    already-computed synthesis instead of discarding it when the final model
    call fails. Empty = no Thinker analysis was produced."""

    def summary(self) -> str:
        """Human-readable one-liner for logs."""
        plan_status = "planned" if self.plan_text else "no-plan"
        verify_count = len(self.verification_results)
        gate = "gate?" if self.gate_passed is None else ("gate=pass" if self.gate_passed else "gate=fail")
        return (
            f"iters={self.iterations_used} steps={len(self.steps)} "
            f"hit_limit={self.hit_limit} clarified={self.clarification_issued} "
            f"plan={plan_status} verify={verify_count} criteria={len(self.success_criteria)} {gate}"
        )

    def work_report(self) -> WorkReport:
        """Return the trace's explicit worker-to-report boundary."""
        return WorkReport.from_trace(self)
