"""
Agent data models — pure dataclasses, no business logic.

Kept separate so that engine.py, tests, and UI serialization layers
can import AgentStep / AgentTrace without pulling in the full loop.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from typing import Optional


@dataclass
class AgentStep:
    """Record of a single iteration inside the agent loop."""

    iteration: int
    thought: str
    tool_name: Optional[str]
    tool_input: Optional[str]
    observation: Optional[str]
    reflection: Optional[str] = None
    tool_failed: bool = False
    retry_count: int = 0
    latency_ms: int = 0
    phase: str = "execute"
    """Phase of the workflow: 'plan', 'execute', 'verify', or 'final'."""


@dataclass(frozen=True)
class WorkReportEntry:
    """Evidence returned by one worker/tool operation."""

    tool_name: str
    tool_input: str
    observation: str
    succeeded: bool


@dataclass(frozen=True)
class WorkReport:
    """Structured worker report used at the tool-to-user boundary.

    The report is deliberately deterministic: it is derived from the trace,
    not generated by another model call. This gives the orchestrator a stable
    report-back contract when model synthesis is empty or merely a heading.
    """

    entries: tuple[WorkReportEntry, ...] = ()
    hit_limit: bool = False

    @classmethod
    def from_trace(cls, trace: "AgentTrace") -> "WorkReport":
        return cls(
            entries=tuple(
                WorkReportEntry(
                    tool_name=step.tool_name or "",
                    tool_input=step.tool_input or "",
                    observation=step.observation or "",
                    succeeded=not step.tool_failed,
                )
                for step in trace.steps
                if step.tool_name
            ),
            hit_limit=trace.hit_limit,
        )

    def needs_report(self, response: str) -> bool:
        """Return whether a response failed to report tool evidence."""
        if not self.entries:
            return False
        if not response.strip():
            return True

        # Evidence comes from tool observations, not commands. A command such
        # as ``ls Dev`` should not make a heading like "Here's the result"
        # appear complete merely because it repeats the command.
        evidence_tokens: set[str] = set()
        ignored = {
            "true",
            "false",
            "none",
            "null",
            "okay",
            "success",
            "successful",
            "status",
            "result",
            "output",
            "tool",
            "command",
            "completed",
        }
        for entry in self.entries:
            if not entry.observation.strip():
                continue
            for token in re.findall(
                r"[a-z0-9][a-z0-9_.:/\\-]{3,}", entry.observation.lower()
            ):
                if token not in ignored:
                    evidence_tokens.add(token)

        # Side-effect-only tools often return only "OK". A normal concise
        # confirmation is sufficient when there is no substantive evidence to
        # report; the report is required for listings, search results, etc.
        if not evidence_tokens:
            return False
        normalized_response = response.lower()
        matched_tokens = sum(
            token in normalized_response for token in evidence_tokens
        )
        required_tokens = min(2, len(evidence_tokens))
        return matched_tokens < required_tokens

    def render(self) -> str:
        """Render the deterministic report for the user-facing stream."""
        if not self.entries:
            return ""

        lines = ["Worker report — tool execution evidence:"]
        if self.hit_limit:
            lines.append("The agent loop reached its iteration limit after these operations:")
        for index, entry in enumerate(self.entries, 1):
            status = "succeeded" if entry.succeeded else "failed"
            tool_input = entry.tool_input.strip() or "(no input recorded)"
            lines.append(f"{index}. {entry.tool_name}({tool_input}) — {status}")
            output = entry.observation.strip() or "(no output returned)"
            if len(output) > 500:
                output = output[:497] + "..."
            lines.append(f"   Output: {output}")
        return "\n".join(lines)


@dataclass
class AgentTrace:
    """Accumulated trace for a complete agent run."""

    steps: list[AgentStep] = field(default_factory=list)
    final_response: str = ""
    iterations_used: int = 0
    hit_limit: bool = False
    clarification_issued: bool = False
    tool_talk_recoveries: int = 0  # how many times tool-talk was detected and suppressed
    plan_text: str = ""
    """Text of the planning phase output (empty if planning was skipped)."""
    verification_results: list[str] = field(default_factory=list)
    """Results from post-execution verification checks."""

    def summary(self) -> str:
        """Human-readable one-liner for logs."""
        plan_status = "planned" if self.plan_text else "no-plan"
        verify_count = len(self.verification_results)
        return (
            f"iters={self.iterations_used} steps={len(self.steps)} "
            f"hit_limit={self.hit_limit} clarified={self.clarification_issued} "
            f"plan={plan_status} verify={verify_count}"
        )

    def work_report(self) -> WorkReport:
        """Return the trace's explicit worker-to-report boundary."""
        return WorkReport.from_trace(self)
